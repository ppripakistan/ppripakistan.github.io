#!/usr/bin/env python3
"""
scripts/build_brand_assets_v2.py
Processes PPRI master brand assets and generates:
1. Header & footer logos: ppri-logo-header.jpg, ppri-logo-header.png
2. Schema & master logo: ppri-logo.jpg, ppri-logo.png (512x512 1:1 square)
3. Complete pure emblem favicon suite:
   - root & brand favicon.ico (multi-res 16, 32, 48 transparent)
   - root & brand favicon.png (512x512 transparent)
   - root & brand favicon.svg (512x512 transparent)
   - root & brand apple-touch-icon.png (180x180 solid background)
   - brand favicon-16x16.png, favicon-32x32.png, favicon-48x48.png, icon-192.png, icon-512.png, ppri-favicon.png

Note: Social preview cards are solely and authoritatively generated by
scripts/generate_social_previews.py into assets/images/previews/.
"""

import os
import io
import base64
from pathlib import Path
from PIL import Image

ROOT_DIR = Path(__file__).resolve().parent.parent
BRAND_DIR = ROOT_DIR / "assets" / "images" / "brand"
RESEARCH_DIR = ROOT_DIR / "assets" / "images" / "research"
NEW_LOGO_PATH = BRAND_DIR / "ppri-logo-master.webp"
COMPLETE_LOGO_PATH = BRAND_DIR / "ppri-complete-logo.png"

BRAND_DIR.mkdir(parents=True, exist_ok=True)
RESEARCH_DIR.mkdir(parents=True, exist_ok=True)

def load_master_logo():
    if not NEW_LOGO_PATH.exists():
        raise FileNotFoundError(f"Master logo not found at {NEW_LOGO_PATH}")
    return Image.open(NEW_LOGO_PATH).convert('RGB')

def get_cropped_composite_square(im):
    """
    Crops the composite logo (emblem + PPRI + subtitle) tightly and places it on a clean square canvas.
    Composite bbox: X: 336..1678, Y: 368..1639.
    Center is ~(1007, 1003). Height is 1271, width is 1342.
    """
    w, h = im.size
    cx, cy = 1007, 1003
    half_size = int(max(1342, 1271) * 0.55)  # ~738
    box = (max(0, cx - half_size), max(0, cy - half_size), min(w, cx + half_size), min(h, cy + half_size))
    cropped = im.crop(box)
    square = Image.new('RGB', (half_size * 2, half_size * 2), (255, 255, 255))
    square.paste(cropped, (0, 0))
    return square

def get_emblem_square():
    """
    Extracts strictly the pure geometric shield emblem without any abbreviation or text.
    In ppri-complete-logo.png:
      Emblem bbox: X: 357..1019, Y: 0..678.
      Separated from 'PPRI' text (which begins at Y=746) by a 68px transparent gap.
    Returns a centered, high-resolution RGBA square with transparent background.
    """
    if COMPLETE_LOGO_PATH.exists():
        im = Image.open(COMPLETE_LOGO_PATH).convert('RGBA')
        emblem_crop = im.crop((357, 0, 1019, 678))
    else:
        master = Image.open(NEW_LOGO_PATH).convert('RGBA')
        emblem_crop = master.crop((692, 367, 1356, 1045))

    # Tight bbox of the emblem artwork
    bbox = emblem_crop.getbbox()
    if bbox:
        emblem_tight = emblem_crop.crop(bbox)
    else:
        emblem_tight = emblem_crop

    # Create a balanced transparent square canvas with ~4% breathing margin
    w, h = emblem_tight.size
    dim = max(w, h)
    pad = int(dim * 0.04)
    canvas_dim = dim + pad * 2
    square = Image.new('RGBA', (canvas_dim, canvas_dim), (0, 0, 0, 0))
    offset_x = (canvas_dim - w) // 2
    offset_y = (canvas_dim - h) // 2
    square.paste(emblem_tight, (offset_x, offset_y), emblem_tight)
    return square

def generate_logo_and_favicons():
    print("Loading master logos...")
    master = load_master_logo()
    composite_square = get_cropped_composite_square(master)
    emblem_square = get_emblem_square()

    # 1. ppri-logo.jpg & ppri-logo.png (512x512 1:1 square for schema and master branding)
    print("Generating ppri-logo.png and ppri-logo.jpg (512x512)...")
    logo_512 = composite_square.resize((512, 512), Image.Resampling.LANCZOS)
    logo_512.save(BRAND_DIR / "ppri-logo.png", format="PNG", optimize=True)
    logo_512.save(BRAND_DIR / "ppri-logo.jpg", format="JPEG", quality=95, optimize=True)

    # 2. ppri-logo-header.png & ppri-logo-header.jpg (240x240 for header badge and footer)
    print("Generating ppri-logo-header.png and ppri-logo-header.jpg (240x240)...")
    logo_240 = composite_square.resize((240, 240), Image.Resampling.LANCZOS)
    logo_240.save(BRAND_DIR / "ppri-logo-header.png", format="PNG", optimize=True)
    logo_240.save(BRAND_DIR / "ppri-logo-header.jpg", format="JPEG", quality=95, optimize=True)

    # 3. Favicon suite (EMBLEM ONLY - No text or abbreviation)
    print("Generating pure emblem favicon suite...")
    # Root & Brand favicon.png (512x512 RGBA transparent)
    fav_512 = emblem_square.resize((512, 512), Image.Resampling.LANCZOS)
    fav_512.save(ROOT_DIR / "favicon.png", format="PNG", optimize=True)
    fav_512.save(BRAND_DIR / "favicon.png", format="PNG", optimize=True)

    # Root & Brand apple-touch-icon.png (180x180 solid background for iOS HIG)
    apple_canvas = Image.new('RGB', (180, 180), (255, 255, 255))
    apple_emb = emblem_square.resize((156, 156), Image.Resampling.LANCZOS)
    apple_canvas.paste(apple_emb, (12, 12), apple_emb)
    apple_canvas.save(ROOT_DIR / "apple-touch-icon.png", format="PNG", optimize=True)
    apple_canvas.save(BRAND_DIR / "apple-touch-icon.png", format="PNG", optimize=True)

    # Standard favicon PNG sizes (RGBA transparent)
    for sz, name in [
        (16, "favicon-16x16.png"),
        (32, "favicon-32x32.png"),
        (48, "favicon-48x48.png"),
        (192, "icon-192.png"),
        (512, "icon-512.png"),
        (192, "ppri-favicon.png")
    ]:
        resized = emblem_square.resize((sz, sz), Image.Resampling.LANCZOS)
        resized.save(BRAND_DIR / name, format="PNG", optimize=True)

    # Multi-resolution favicon.ico (16, 32, 48) RGBA
    fav_ico_master = emblem_square.resize((48, 48), Image.Resampling.LANCZOS)
    fav_ico_master.save(ROOT_DIR / "favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)])
    fav_ico_master.save(BRAND_DIR / "favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)])

    # Root & Brand favicon.svg (Pure emblem vector container)
    emb_buf = io.BytesIO()
    fav_512.save(emb_buf, format="PNG", optimize=True)
    b64_data = base64.b64encode(emb_buf.getvalue()).decode('ascii')
    svg_content = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="100%" height="100%">
  <image width="512" height="512" href="data:image/png;base64,{b64_data}"/>
</svg>
'''
    (ROOT_DIR / "favicon.svg").write_text(svg_content, encoding="utf-8")
    (BRAND_DIR / "favicon.svg").write_text(svg_content, encoding="utf-8")
    print("  Generated favicon.svg in root and brand/")

    return emblem_square, composite_square

if __name__ == '__main__':
    emblem, composite = generate_logo_and_favicons()
    print("All logo and pure emblem favicon assets successfully generated!")
